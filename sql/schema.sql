CREATE EXTENSION IF NOT EXISTS vector;
CREATE TABLE IF NOT EXISTS games (
 id BIGSERIAL PRIMARY KEY, title TEXT UNIQUE NOT NULL, description TEXT NOT NULL,
 genres TEXT[] NOT NULL DEFAULT '{}', platforms TEXT[] NOT NULL DEFAULT '{}',
 pricing_model TEXT NOT NULL DEFAULT 'Paid', embedding vector(384), created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS games_genres_idx ON games USING GIN(genres);
CREATE INDEX IF NOT EXISTS games_platforms_idx ON games USING GIN(platforms);
CREATE TABLE IF NOT EXISTS reviews (
 id BIGSERIAL PRIMARY KEY, game_id BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
 username TEXT NOT NULL, rating SMALLINT NOT NULL CHECK(rating BETWEEN 1 AND 5),
 body TEXT NOT NULL CHECK(char_length(body) BETWEEN 5 AND 1000),
 is_fictional BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS users (
 id BIGSERIAL PRIMARY KEY, username TEXT UNIQUE NOT NULL, created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS user_library (
 user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
 game_id BIGINT REFERENCES games(id) ON DELETE CASCADE, added_at TIMESTAMPTZ DEFAULT now(),
 PRIMARY KEY(user_id, game_id)
);
CREATE TABLE IF NOT EXISTS demo_wallets (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 credits INTEGER NOT NULL DEFAULT 100 CHECK(credits >= 0)
);
